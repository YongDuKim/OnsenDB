import { PREF_COORD } from '../schema'
import type { OnsenRecord } from '../types'

/** 地図投影(簡易正距円筒) */
export const proj = (lat: number, lng: number) => ({ x: (lng - 128.6) * 40, y: (46.3 - lat) * 47 })

export interface RecordPos {
  lat: number
  lng: number
  exact: boolean
}

/** レコードの地図上の位置。座標入力があれば実位置、なければ県代表点 */
export function recordPosition(rec: OnsenRecord): RecordPos | null {
  if (rec.lat != null && rec.lng != null) return { lat: rec.lat, lng: rec.lng, exact: true }
  const c = PREF_COORD[rec.pref]
  if (c) return { lat: c[0], lng: c[1], exact: false }
  return null
}

