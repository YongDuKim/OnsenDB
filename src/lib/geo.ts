export const coastPath = (pts: [number, number][]): string =>
  'M' +
  pts
    .map(([la, lo]) => {
      const p = proj(la, lo)
      return `${p.x.toFixed(1)},${p.y.toFixed(1)}`
    })
    .join('L') +
  'Z'
